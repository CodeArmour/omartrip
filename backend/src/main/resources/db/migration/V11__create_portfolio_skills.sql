CREATE TABLE portfolio_skills (
    id UUID PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    category VARCHAR(80),
    logo_url VARCHAR(500) NOT NULL,
    logo_public_id VARCHAR(255),
    display_order INTEGER NOT NULL,
    published BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

CREATE UNIQUE INDEX uq_portfolio_skills_name_lower ON portfolio_skills (LOWER(name));
CREATE UNIQUE INDEX uq_portfolio_skills_logo_public_id ON portfolio_skills (logo_public_id) WHERE logo_public_id IS NOT NULL;
CREATE INDEX idx_portfolio_skills_public_order ON portfolio_skills (published, display_order);

